#!/usr/bin/env python3
"""Add bounded private memory RPCs after the pinned socket/shadow preparation.

No default feature is enabled. Only a PRIVATE_INDEXED_WSI encoder build selects
chunking, and only for the non-direct socket transport. Existing public/direct
entrypoints delegate to their original generated implementation.
"""
import hashlib
from pathlib import Path
import shutil
import subprocess
import sys
from prepare_mesa import replace_once, SOURCES

HERE = Path(__file__).resolve().parent
PREFIX = 'src/gfxstream/guest/vulkan_enc/'
FILES = ['autogenerated/VkEncoder.cpp', 'autogenerated/VkEncoder.h',
         'ResourceTracker.cpp', 'ResourceTracker.h']
HEADERS = ('ranges.h', 'flush_window.h', 'flush_packet.h', 'flush_timing.h', 'rpc_timing.h')
TIMED_RPCS = (
    'vkQueueSubmit',
    'vkQueueWaitIdle',
    'vkDeviceWaitIdle',
    'vkResetFences',
    'vkWaitForFences',
    'vkBeginCommandBuffer',
    'vkEndCommandBuffer',
    'vkResetCommandBuffer',
    'vkAllocateDescriptorSets',
    'vkResetDescriptorPool',
)
PIN = '541c56aa3fd24027ed46ae350287d21dcd56c901'


def instrument_rpc_call(encoder, name):
    anchor = f'VkResult VkEncoder::{name}('
    if encoder.count(anchor) != 1:
        raise ValueError(f'expected once: {anchor}')
    start = encoder.index(anchor)
    end = encoder.index('\n}\n', start) + 3
    body = encoder[start:end]
    if 'VALIDATE_RET' in body or 'validation()' in body:
        raise ValueError(f'unexpected pre-lock validation in {name}')
    old_head = '''    (void)doLock;
    bool queueSubmitWithCommandsEnabled =
        sFeatureBits & VULKAN_STREAM_FEATURE_QUEUE_SUBMIT_WITH_COMMANDS_BIT;
    if (!queueSubmitWithCommandsEnabled && doLock) this->lock();'''
    new_head = f'''    (void)doLock;
    static_assert(caboose::memory::timedRpcIndex(OP_{name}) >= 0, "untimed RPC opcode");
    caboose::memory::RpcCallScope caboose_rpc_timing{{OP_{name}}};
    bool queueSubmitWithCommandsEnabled =
        sFeatureBits & VULKAN_STREAM_FEATURE_QUEUE_SUBMIT_WITH_COMMANDS_BIT;
    if (!queueSubmitWithCommandsEnabled && doLock) caboose_rpc_timing.lock([&] {{ this->lock(); }});'''
    old_tail = f'''    if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();
    return {name}_VkResult_return;
}}'''
    new_tail = f'''    if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();
    return static_cast<VkResult>(caboose_rpc_timing.finish({name}_VkResult_return));
}}'''
    body = replace_once(body, old_head, new_head)
    body = replace_once(body, old_tail, new_tail)
    return encoder[:start] + body + encoder[end:]


def transform(encoder, encoder_h, tracker, tracker_h):
    if 'cabooseFlushMemoryChunk' in encoder or 'cabooseMappedRange' in tracker:
        raise ValueError('bounded memory patch already applied')
    if 'socketReadbacks' not in encoder or 'socketShadow' not in tracker:
        raise ValueError('requires the prepared socket/shadow memory path')
    for original, helper in [('vkFlushMappedMemoryRanges', 'cabooseFlushMemoryChunk'),
                             ('vkInvalidateMappedMemoryRanges', 'cabooseInvalidateMemoryChunk')]:
        encoder = replace_once(encoder, 'VkResult VkEncoder::' + original + '(',
                                'VkResult VkEncoder::' + helper + '(')
    begin_flush = encoder.index('VkResult VkEncoder::cabooseFlushMemoryChunk(')
    end_flush = encoder.index('VkResult VkEncoder::cabooseInvalidateMemoryChunk(', begin_flush)
    flush = encoder[begin_flush:end_flush]
    flush = replace_once(flush, 'uint32_t doLock) {', 'uint32_t doLock, bool deferReply) {')
    validation = '''    VALIDATE_RET(VkResult, VK_SUCCESS,
                 mImpl->validation()->on_vkFlushMappedMemoryRanges(
                     this, VK_SUCCESS, device, memoryRangeCount, pMemoryRanges));'''
    flush = replace_once(flush, validation,
        '    if (deferReply && (queueSubmitWithCommandsEnabled || sResourceTracker->usingDirectMapping())) return VK_ERROR_FEATURE_NOT_PRESENT;\n' +
        '    if (!deferReply) {\n' + validation + '\n    }')
    flush = replace_once(flush,
        '    if (!stream->tryRead(&vkFlushMappedMemoryRanges_VkResult_return, sizeof(VkResult))) {',
        '    if (!deferReply && !stream->tryRead(&vkFlushMappedMemoryRanges_VkResult_return, sizeof(VkResult))) {')
    encoder = encoder[:begin_flush] + flush + encoder[end_flush:]
    begin = encoder.index('VkResult VkEncoder::cabooseInvalidateMemoryChunk(')
    end = encoder.index('void VkEncoder::vkGetDeviceMemoryCommitment(', begin)
    part = encoder[begin:end]
    part = replace_once(part, 'uint32_t doLock) {', 'uint32_t doLock, uint8_t* socketDestination) {')
    # The transaction supplies bounded storage. The original publication path
    # remains byte-for-byte for the ordinary/public/direct call.
    old = '''            try {
                socketReadbacks.emplace_back(hostPtr + offset, std::vector<uint8_t>(actualSize));'''
    new = '''            if (socketDestination) {
                if (memoryRangeCount != 1 || !stream->tryRead(socketDestination, actualSize)) {
                    stream->invalidate();
                    if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();
                    return VK_ERROR_DEVICE_LOST;
                }
                continue;
            }
            try {
                socketReadbacks.emplace_back(hostPtr + offset, std::vector<uint8_t>(actualSize));'''
    part = replace_once(part, old, new)
    encoder = encoder[:begin] + part + encoder[end:]
    for rpc_name in TIMED_RPCS:
        encoder = instrument_rpc_call(encoder, rpc_name)
    wrappers = (HERE / 'bounded-memory/encoder_wrappers.inc').read_text()
    encoder = replace_once(encoder, 'VkResult VkEncoder::cabooseFlushMemoryChunk(',
                           wrappers + '\nVkResult VkEncoder::cabooseFlushMemoryChunk(')
    includes = ''.join(f'#include "caboose-bounded-memory/{h}"\n' for h in HEADERS)
    encoder = includes + encoder
    declaration = '''    VkResult cabooseFlushMemoryChunk(VkDevice device, uint32_t memoryRangeCount,
        const VkMappedMemoryRange* pMemoryRanges, uint32_t doLock, bool deferReply = false);
    VkResult cabooseInvalidateMemoryChunk(VkDevice device, uint32_t memoryRangeCount,
        const VkMappedMemoryRange* pMemoryRanges, uint32_t doLock, uint8_t* socketDestination);
'''
    encoder_h = replace_once(encoder_h, '    VkResult vkFlushMappedMemoryRanges(',
                              declaration + '    VkResult vkFlushMappedMemoryRanges(')
    tracker_h = '#include "caboose-bounded-memory/ranges.h"\n' + tracker_h
    tracker_h = replace_once(tracker_h, '    uint32_t getStreamFeatures() const;',
        '''    bool cabooseMappedRange(VkDevice device, VkDeviceMemory memory, caboose::memory::Range& out);
    uint32_t getStreamFeatures() const;''')
    method = '''bool ResourceTracker::cabooseMappedRange(VkDevice device, VkDeviceMemory memory,
                                         caboose::memory::Range& out) {
    std::lock_guard<std::recursive_mutex> lock(mLock);
    auto found = info_VkDeviceMemory.find(memory);
    auto owner = info_VkDevice.find(device);
    if (found == info_VkDeviceMemory.end() || owner == info_VkDevice.end()) return false;
    const auto& info = found->second;
    if (info.device != device || !info.socketShadow || !info.socketMapped ||
        info.socketMapOffset > info.allocationSize ||
        info.socketMapSize > info.allocationSize - info.socketMapOffset) return false;
    out.base = info.ptr; out.lifetime = info.socketShadow;
    out.mapBegin = info.socketMapOffset;
    out.mapEnd = info.socketMapOffset + info.socketMapSize;
    out.allocation = info.allocationSize;
    out.atom = owner->second.props.limits.nonCoherentAtomSize;
    return true;
}

'''
    tracker = replace_once(tracker, 'VkDeviceSize ResourceTracker::getMappedSize(',
                            method + 'VkDeviceSize ResourceTracker::getMappedSize(')
    return encoder, encoder_h, tracker, tracker_h


def apply(root, check=False):
    root = Path(root)
    if subprocess.check_output(['git', '-C', str(root), 'rev-parse', 'HEAD'], text=True).strip() != PIN:
        raise ValueError('unexpected Mesa revision')
    hashes = dict(SOURCES)
    hashes[PREFIX + FILES[1]] = 'b09806e94640108fa8efa7b300cf16712cff81c10499d9fb40942dae7cbe691d'
    for name in FILES:
        original = subprocess.check_output(['git', '-C', str(root), 'show', 'HEAD:' + PREFIX + name])
        if hashlib.sha256(original).hexdigest() != hashes[PREFIX + name]:
            raise ValueError('unexpected upstream file: ' + name)
    output = transform(*[(root / PREFIX / name).read_text() for name in FILES])
    target = root / PREFIX / 'caboose-bounded-memory'
    if target.exists(): raise ValueError('bounded memory include directory already exists')
    if check: return
    target.mkdir()
    for header in HEADERS:
        shutil.copyfile(HERE / 'bounded-memory' / header, target / header)
    for name, text in zip(FILES, output):
        (root / PREFIX / name).write_text(text)


if __name__ == '__main__':
    if len(sys.argv) not in (2, 3) or (len(sys.argv) == 3 and sys.argv[2] != '--check'):
        raise SystemExit('usage: prepare_bounded_memory.py PREPARED_PRIVATE_MESA [--check]')
    apply(sys.argv[1], len(sys.argv) == 3)
