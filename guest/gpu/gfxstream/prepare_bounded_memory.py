            f'    uint8_t* streamPtr = stream->reserve({pkt_var});\n'
            f'    if (!streamPtr) {{\n'
            f'        pool->freeAll();\n'
            f'        stream->clearPool();\n'
            f'        if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();\n'
            f'        return;\n'
            f'    }}\n'
            f'    uint8_t** streamPtrPtr = &streamPtr;'
