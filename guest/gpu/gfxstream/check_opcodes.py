#!/usr/bin/env python3
"""Compare the opcode tables in the two candidate upstream revisions.

This is a necessary, not sufficient, wire compatibility check. It fetches only
individual source files; it does not build or install either project.
"""
import base64
import hashlib
import re
import urllib.request

MESA = '541c56aa3fd24027ed46ae350287d21dcd56c901'
GFXSTREAM = 'f0ce013371a68e85b5a1a1b0cf14ac9ad729f4be'
GUEST = f'https://android.googlesource.com/platform/external/mesa3d/+/{MESA}/src/gfxstream/guest/vulkan_enc/autogenerated/goldfish_vk_marshaling_guest.h?format=TEXT'
HOST = f'https://raw.githubusercontent.com/google/gfxstream/{GFXSTREAM}/host/vulkan/cereal/common/goldfish_vk_marshaling.h'
PATTERN = re.compile(rb'^\s*#\s*define\s+(OP_vk\w+)\s+(\d+)\s*$', re.M)


def opcodes(data):
    result = {}
    for name, value in PATTERN.findall(data):
        name, value = name.decode(), int(value)
        if name in result and result[name] != value:
            raise ValueError(f'conflicting definitions: {name}')
        result[name] = value
    if not result:
        raise ValueError('no Vulkan opcodes found')
    return result


def main():
    with urllib.request.urlopen(GUEST, timeout=30) as response:
        guest = base64.b64decode(response.read(), validate=True)
    with urllib.request.urlopen(HOST, timeout=30) as response:
        host = response.read()
    expected = ('8dd2b5b8f846074fb834f8dda2f1c81cb8009428c5e73ad638b2e8adb577a270',
                '2174da9a4aaf50d228c36537c6b6fc3c66ccec8e8ce1c6c761e225da1488a302')
    if tuple(hashlib.sha256(data).hexdigest() for data in (guest, host)) != expected:
        raise ValueError('source hash mismatch')
    a, b = opcodes(guest), opcodes(host)
    print('guest sha256:', hashlib.sha256(guest).hexdigest())
    print('host sha256: ', hashlib.sha256(host).hexdigest())
    mismatch = [(name, a[name], b.get(name)) for name in sorted(a) if a[name] != b.get(name)]
    print(f'guest {len(a)}, host {len(b)}, guest mismatches {len(mismatch)}, host-only {len(b.keys() - a.keys())}')
    for name, guest_value, host_value in mismatch:
        print(f'{name}: guest={guest_value} host={host_value}')
    return bool(mismatch)


if __name__ == '__main__':
    raise SystemExit(main())
