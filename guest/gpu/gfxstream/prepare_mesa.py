def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError('unexpected upstream source: ' + old)
    return text.replace(old, new, 1)


def prepare(root):
    revision = subprocess.check_output(['git', '-C', str(root), 'rev-parse', 'HEAD'], text=True).strip()
    if revision != '541c56aa3fd24027ed46ae350287d21dcd56c901':
        raise ValueError('unexpected Mesa HEAD')
    if subprocess.check_output(['git', '-C', str(root), 'status', '--porcelain', '--untracked-files=no'], text=True):
        raise ValueError('Mesa checkout has tracked modifications')
    paths = {name: root / name for name in SOURCES}
    contents = {}
    for name, path in paths.items():
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != SOURCES[name]:
            raise ValueError(f'{name}: source hash mismatch')
        contents[name] = data.decode('utf-8')
    manager, meson, device, encoder, tracker, tracker_h, iostream, vkstream = SOURCES
    contents[manager] = replace_once(contents[manager], '#include <cerrno>', '#include <cerrno>\n#include <cstdlib>\n#include "SocketStream.h"')
    contents[manager] = replace_once(contents[manager], '    switch (mTransportType) {', '''    if (const char* path = std::getenv("CABOOSE_GFXSTREAM_SOCKET")) {
        if (!*path) return false;
        auto stream = new CabooseSocketStream(STREAM_BUFFER_SIZE);
        if (stream->connect(path) < 0) { delete stream; return false; }
        mStream = stream;
    } else switch (mTransportType) {''')
    contents[meson] = replace_once(contents[meson], "    'GfxStreamConnectionManager.cpp',", "    'GfxStreamConnectionManager.cpp',\n    'SocketStream.cpp',")
    # The socket path cannot yet implement host-visible Vulkan memory or process
    # association. Reject it before connecting or exposing a physical device.
    contents[device] = replace_once(contents[device], 'static VkResult SetupInstanceForProcess(void) {', '''static VkResult SetupInstanceForProcess(void) {
    if (std::getenv("CABOOSE_GFXSTREAM_SOCKET")) return VK_ERROR_INCOMPATIBLE_DRIVER;''')
    contents[device] = '#include <cstdlib>\n' + contents[device]
    old_size = 'size == VK_WHOLE_SIZE ? sResourceTracker->getMappedSize(memory) : size'
    new_size = 'size == VK_WHOLE_SIZE ? sResourceTracker->getMappedSize(memory) - offset : size'
    if contents[encoder].count(old_size) != 2:
        raise ValueError('unexpected generated flush/invalidate range calculation')
    contents[encoder] = contents[encoder].replace(old_size, new_size)
    # VALIDATE_RET returns immediately, so validate before acquiring the encoder lock.
    for function in ('vkFlushMappedMemoryRanges', 'vkInvalidateMappedMemoryRanges'):
        begin = contents[encoder].index('VkResult VkEncoder::' + function + '(')
        end = contents[encoder].index('    auto stream = mImpl->stream();', begin)
        section = contents[encoder][begin:end]
        lock_line = '    if (!queueSubmitWithCommandsEnabled && doLock) this->lock();\n'
        section = replace_once(section, lock_line, '') + lock_line
        contents[encoder] = contents[encoder][:begin] + section + contents[encoder][end:]
    # The host maps the entire allocation. Canonicalize WHOLE_SIZE before
    # marshaling so it ends at the guest's potentially smaller mapping.
    anchor = '''            transform_tohost_VkMappedMemoryRange(sResourceTracker,
                                                 (VkMappedMemoryRange*)(local_pMemoryRanges + i));'''
    replacement = '''            if (!sResourceTracker->usingDirectMapping() && pMemoryRanges[i].size == VK_WHOLE_SIZE)
                local_pMemoryRanges[i].size = sResourceTracker->getMappedSize(pMemoryRanges[i].memory) - pMemoryRanges[i].offset;
            transform_tohost_VkMappedMemoryRange(sResourceTracker,
                                                 (VkMappedMemoryRange*)(local_pMemoryRanges + i));'''
    start = contents[encoder].index('VkResult VkEncoder::vkFlushMappedMemoryRanges(')
    end = contents[encoder].index('void VkEncoder::vkGetDeviceMemoryCommitment(', start)
    section = contents[encoder][start:end]
    if section.count(anchor) != 2:
        raise ValueError('unexpected mapped range marshaling')
    contents[encoder] = contents[encoder][:start] + section.replace(anchor, replacement) + contents[encoder][end:]

    start = contents[encoder].index('VkResult VkEncoder::vkInvalidateMappedMemoryRanges(')
    end = contents[encoder].index('void VkEncoder::vkGetDeviceMemoryCommitment(', start)
    part = contents[encoder][start:end]
    anchor = '''            stream->read(&streamSize, sizeof(uint64_t));
            uint8_t* targetRange = hostPtr + offset;'''
    for condition in ('!memory', '!hostPtr'):
        missing = '''            if (CONDITION) {
                stream->read(&streamSize, sizeof(uint64_t));
                continue;
            };'''.replace('CONDITION', condition)
        terminal = '''            if (CONDITION) {
                stream->invalidate();
                if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();
                return VK_ERROR_DEVICE_LOST;
            };'''.replace('CONDITION', condition)
        part = replace_once(part, missing, terminal)
    part = replace_once(part, anchor, '''            stream->read(&streamSize, sizeof(uint64_t));
            if (streamSize != actualSize) {
                stream->invalidate();
                if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();
                return VK_ERROR_DEVICE_LOST;
            }
            uint8_t* targetRange = hostPtr + offset;''')
    contents[encoder] = contents[encoder][:start] + part + contents[encoder][end:]
    # These two entrypoints can report an incomplete response without aborting.
    # Other entrypoints still use upstream's aborting read; the ICD gate stays.
    start_flush = contents[encoder].index('VkResult VkEncoder::vkFlushMappedMemoryRanges(')
    end_flush = contents[encoder].index('VkResult VkEncoder::vkInvalidateMappedMemoryRanges(', start_flush)
    flush = contents[encoder][start_flush:end_flush]
    flush = replace_once(flush,
        '    stream->read(&vkFlushMappedMemoryRanges_VkResult_return, sizeof(VkResult));',
        '''    if (!stream->tryRead(&vkFlushMappedMemoryRanges_VkResult_return, sizeof(VkResult))) {
        if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();
        return VK_ERROR_DEVICE_LOST;
    }''')
    contents[encoder] = contents[encoder][:start_flush] + flush + contents[encoder][end_flush:]
    start_inv = contents[encoder].index('VkResult VkEncoder::vkInvalidateMappedMemoryRanges(')
    end_inv = contents[encoder].index('void VkEncoder::vkGetDeviceMemoryCommitment(', start_inv)
    inv = contents[encoder][start_inv:end_inv]
    inv = replace_once(inv,
        '    stream->read(&vkInvalidateMappedMemoryRanges_VkResult_return, sizeof(VkResult));',
        '''    if (!stream->tryRead(&vkInvalidateMappedMemoryRanges_VkResult_return, sizeof(VkResult))) {
        if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();
        return VK_ERROR_DEVICE_LOST;
    }
    std::vector<std::pair<uint8_t*, std::vector<uint8_t>>> socketReadbacks;''')
    inv = replace_once(inv,
        '            stream->read(&streamSize, sizeof(uint64_t));\n            if (streamSize != actualSize)',
        '''            if (!stream->tryRead(&streamSize, sizeof(uint64_t))) {
                if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();
                return VK_ERROR_DEVICE_LOST;
            }
            if (streamSize != actualSize)''')
    inv = replace_once(inv, '''            uint8_t* targetRange = hostPtr + offset;
            stream->read(targetRange, actualSize);''',
        '''            try {
                socketReadbacks.emplace_back(hostPtr + offset, std::vector<uint8_t>(actualSize));
            } catch (const std::exception&) {
                stream->invalidate();
                if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();
                return VK_ERROR_OUT_OF_HOST_MEMORY;
            }
            auto& readback = socketReadbacks.back().second;
            if (!stream->tryRead(readback.data(), readback.size())) {
                if (!queueSubmitWithCommandsEnabled && doLock) this->unlock();
                return VK_ERROR_DEVICE_LOST;
            }''')
    inv = replace_once(inv, '    ++encodeCount;', '''    if (vkInvalidateMappedMemoryRanges_VkResult_return == VK_SUCCESS) {
        for (auto& entry : socketReadbacks)
            memcpy(entry.first, entry.second.data(), entry.second.size());
    }
    ++encodeCount;''')
    contents[encoder] = contents[encoder][:start_inv] + inv + contents[encoder][end_inv:]
    contents[encoder] = '#include <exception>\n' + contents[encoder]
    contents[iostream] = replace_once(contents[iostream],
        '    virtual uint64_t processPipeInit() { return 0; }',
        '    virtual uint64_t processPipeInit() { return 0; }\n    virtual void invalidate() {}')
    contents[vkstream] = replace_once(contents[vkstream],
        '    // Returns whether the connection is valid.',
        '''    void invalidate() { if (mStream) mStream->invalidate(); }
    bool tryRead(void* data, size_t size) {
        if (size == 0) return true;
        if (mStream && mStream->readback(data, size)) return true;
        invalidate();
        return false;
    }

    // Returns whether the connection is valid.''')
    contents[tracker] = '#include <cstdlib>\n#include <new>\n' + contents[tracker]
    contents[tracker] = replace_once(contents[tracker],
        'bool ResourceTracker::usingDirectMapping() const { return true; }',
        'bool ResourceTracker::usingDirectMapping() const { return !std::getenv("CABOOSE_GFXSTREAM_SOCKET"); }')
    contents[tracker_h] = replace_once(contents[tracker_h],
        '        uint8_t* ptr = nullptr;',
        '        uint8_t* ptr = nullptr;\n        std::shared_ptr<uint8_t> socketShadow;\n        bool socketMapped = false;\n        VkDeviceSize socketMapOffset = 0;\n        VkDeviceSize socketMapSize = 0;')
    contents[tracker] = replace_once(contents[tracker],
        '    const bool requestedMemoryIsHostVisible =\n        isHostVisible(&physicalDeviceMemoryProps, pAllocateInfo->memoryTypeIndex);',
        '    const bool requestedMemoryIsHostVisible =\n        isHostVisible(&physicalDeviceMemoryProps, pAllocateInfo->memoryTypeIndex);\n' +
        (HERE / 'shadow_allocation.inc').read_text())
    contents[tracker] = replace_once(contents[tracker],
        '    return info.allocationSize;\n}\n\nbool ResourceTracker::isValidMemoryRange',
        '    return info.socketShadow ? info.socketMapOffset + info.socketMapSize : info.allocationSize;\n}\n\nbool ResourceTracker::isValidMemoryRange')
    contents[tracker] = replace_once(contents[tracker],
        '    if (!info.ptr) return false;\n\n    VkDeviceSize offset = range.offset;',
        '    if (!info.ptr) return false;\n' + (HERE / 'shadow_validate.inc').read_text() +
        '\n    VkDeviceSize offset = range.offset;')
    contents[tracker] = replace_once(contents[tracker],
        '    auto& deviceMemoryInfo = deviceMemoryInfoIt->second;\n\n    if (deviceMemoryInfo.blobId',
        '    auto& deviceMemoryInfo = deviceMemoryInfoIt->second;\n' + (HERE / 'shadow_map.inc').read_text() +
        '\n    if (deviceMemoryInfo.blobId')
    contents[tracker] = replace_once(contents[tracker],
        'void ResourceTracker::on_vkUnmapMemory(void*, VkDevice, VkDeviceMemory) {\n    // no-op\n}',
        '''void ResourceTracker::on_vkUnmapMemory(void*, VkDevice device, VkDeviceMemory memory) {
    std::lock_guard<std::recursive_mutex> lock(mLock);
    auto it = info_VkDeviceMemory.find(memory);
    if (it != info_VkDeviceMemory.end() && it->second.socketShadow && it->second.device == device) {
        it->second.socketMapped = false;
        it->second.socketMapOffset = 0;
        it->second.socketMapSize = 0;
    }
}''')
    contents[tracker] = replace_once(contents[tracker],
        'return offset + size <= info.allocationSize;',
        'return offset <= info.allocationSize && size <= info.allocationSize - offset;')
    target = root / 'src/gfxstream/guest/connection-manager'
    for name in ('SocketStream.h', 'SocketStream.cpp'):
        if (target / name).exists():
            raise ValueError(f'{target / name}: already exists')
    for name, text in contents.items():
        paths[name].write_text(text, encoding='utf-8')
    for name in ('SocketStream.h', 'SocketStream.cpp'):
        shutil.copyfile(HERE / name, target / name)


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit('usage: prepare_mesa.py MESA_SOURCE_TREE')
    prepare(Path(sys.argv[1]))
