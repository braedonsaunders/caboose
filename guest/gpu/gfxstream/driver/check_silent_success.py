#!/usr/bin/env python3
"""Check that silent success names exactly the commands the guest encoder defers.

Under hello 0x800000 the decoder writes no reply for the commands in
caboose-bounded-memory/silent_success.h (kOpcodes, the decoder's
silent-success-opcodes.inc; docs/gpu-live.md, "Silent success"). In a prepared driver
tree every encoder command that registers a deferred handle or checked result must be
listed, and every listed command must either register one or read no reply at all.
compile.sh runs this before every build.

usage: check_silent_success.py PREPARED_MESA_TREE
"""
from pathlib import Path
import re
import sys

ENCODER = 'src/gfxstream/guest/vulkan_enc/autogenerated/VkEncoder.cpp'
DEFINES = 'src/gfxstream/guest/vulkan_enc/autogenerated/goldfish_vk_marshaling_guest.h'
GUEST = 'src/gfxstream/guest/vulkan_enc/caboose-bounded-memory/silent_success.h'
# Registrations of replies silent success leaves out (deferred_replies.h).
SILENCEABLE = re.compile(r'deferredReplies\.(addHandleCreates?|addCheckedResults?)\(')
READS = re.compile(r'\bread\(stream|tryRead\(|stream->read\(')


def guest_opcodes(header):
    """The opcodes in silent_success.h's kOpcodes."""
    table = header.split('kOpcodes[] = {', 1)[1].split('};', 1)[0]
    return [int(value) for value in re.findall(r'^\s*(\d+)u,', table, re.M)]


def encoder_commands(encoder, defines):
    """({opcode: name} of commands that defer a silenceable reply, {opcodes of void commands
    that read no reply}) in the generated encoder."""
    values = {name: int(value) for name, value in re.findall(r'^#define OP_(vk\w+) (\d+)$', defines, re.M)}
    deferred, void = {}, set()
    starts = [m for m in re.finditer(r'^(\w[\w:<>* ]*?)\s+VkEncoder::(\w+)\(', encoder, re.M)]
    for index, start in enumerate(starts):
        end = starts[index + 1].start() if index + 1 < len(starts) else len(encoder)
        body = encoder[start.start():end]
        for name in set(re.findall(r'uint32_t opcode_(vk\w+) = OP_\1;', body)):
            if name not in values:
                continue
            opcode = values[name]
            if SILENCEABLE.search(body):
                deferred[opcode] = name
            elif start.group(1).strip() == 'void' and not READS.search(body):
                void.add(opcode)
    return deferred, void


def differences(deferred, void, listed):
    problems = []
    for opcode, name in sorted(deferred.items()):
        if opcode not in listed:
            problems.append(f'the encoder defers {name} ({opcode}), which silent success does not list')
    for opcode in sorted(listed):
        if opcode not in deferred and opcode not in void:
            problems.append(f'silent success lists {opcode}, whose reply the encoder reads')
    return problems


def main(argv):
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    tree = Path(argv[1])
    deferred, void = encoder_commands((tree / ENCODER).read_text(), (tree / DEFINES).read_text())
    listed = set(guest_opcodes((tree / GUEST).read_text()))
    problems = differences(deferred, void, listed)
    for problem in problems:
        print(f'check_silent_success: {problem}', file=sys.stderr)
    if not problems:
        print(f'check_silent_success: {len(deferred)} deferred and {len(listed & void)} reply-less commands listed')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
