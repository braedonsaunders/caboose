// The icon and manifest (assets/resources.rs), and the service and tray executables when
// CABOOSE_EMBED_DIR names a directory holding release builds of them, so that one
// CabooseSetup.exe carries everything. Without it, setup installs the copies that sit next to
// it (a development build, where `cargo build` puts all three in one directory).
include!("../assets/resources.rs");

fn main() {
    embed_resources();
    println!("cargo:rerun-if-env-changed=CABOOSE_EMBED_DIR");
    println!("cargo:rerun-if-env-changed=CABOOSE_RELEASE_TAG");
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let mut source = String::from("// Generated by build.rs.\n");
    for (constant, file) in [("SERVICE", "caboose-service.exe"), ("TRAY", "caboose-tray.exe")] {
        match std::env::var_os("CABOOSE_EMBED_DIR") {
            Some(directory) => {
                let path = std::path::Path::new(&directory).join(file);
                let path =
                    path.canonicalize().unwrap_or_else(|error| panic!("CABOOSE_EMBED_DIR has no {file}: {error}"));
                println!("cargo:rerun-if-changed={}", path.display());
                source.push_str(&format!("pub const {constant}: Option<&[u8]> = Some(include_bytes!({:?}));\n", path));
            }
            None => source.push_str(&format!("pub const {constant}: Option<&[u8]> = None;\n")),
        }
    }
    std::fs::write(out.join("embedded.rs"), source).expect("write embedded.rs");
}
