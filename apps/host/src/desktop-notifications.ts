import { AgentInputError, AgentNotFoundError, AgentUnavailableError, type AgentGuest } from './agents.js'

/** One of a notification's buttons: the application's action key and its label. */
export interface DesktopNotificationAction { key: string; label: string }
/** An inline reply the application accepts (KDE's `inline-reply`). */
export interface DesktopNotificationReply { label: string; placeholder: string }
export interface DesktopNotification {
  id: string; app: string; summary: string; body: string; created: number
  /** The `desktop-entry` hint, a desktop file ID without `.desktop`. */
  desktopEntry: string | null
  actions: DesktopNotificationAction[]
  /** Whether the application offered `default`, the action of activating the notification. */
  defaultAction: boolean
  reply: DesktopNotificationReply | null
}
/** The owner endpoint's record IDs (guest/notifications/notifycore.py). */
export const NOTIFICATION_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/
const DESKTOP_ENTRY = /^[A-Za-z0-9][A-Za-z0-9._+-]{0,254}$/
const ACTION_KEY = /^[^\u0000-\u001f\u007f]{1,64}$/u
const LABEL = /^[^\u0000-\u001f\u007f]{1,64}$/u
const OPTIONAL_LABEL = /^[^\u0000-\u001f\u007f]{0,64}$/u
const PLACEHOLDER = /^[^\u0000-\u001f\u007f]{0,100}$/u
const BUTTONS = 4
/** Characters (code points) in an inline reply. */
export const REPLY_LIMIT = 2000

function parseActions(value: unknown): DesktopNotificationAction[] | undefined {
  if (value === undefined) return []
  if (!Array.isArray(value) || value.length > BUTTONS) return
  const actions: DesktopNotificationAction[] = []
  for (const item of value) {
    if (!item || typeof item !== 'object' || Array.isArray(item)) return
    const { key, label } = item as Record<string, unknown>
    if (typeof key !== 'string' || !ACTION_KEY.test(key) || key === 'default' || key === 'inline-reply' || actions.some(action => action.key === key)) return
    if (typeof label !== 'string' || !LABEL.test(label)) return
    actions.push({ key, label })
  }
  return actions
}

function parseReply(value: unknown): DesktopNotificationReply | null | undefined {
  if (value === undefined || value === null) return null
  if (typeof value !== 'object' || Array.isArray(value)) return
  const { label, placeholder } = value as Record<string, unknown>
  if (typeof label !== 'string' || !OPTIONAL_LABEL.test(label) || typeof placeholder !== 'string' || !PLACEHOLDER.test(placeholder)) return
  return { label, placeholder }
}

/** Guest records are untrusted; old entries must not reappear after a host restart. */
export function parseDesktopNotification(line: string, now = Date.now()): DesktopNotification | undefined {
  try {
    const value: unknown = JSON.parse(line)
    if (!value || typeof value !== 'object' || Array.isArray(value)) return
    const item = value as Record<string, unknown>
    if (typeof item.id !== 'string' || !NOTIFICATION_ID.test(item.id) || typeof item.app !== 'string' || typeof item.summary !== 'string' || typeof item.body !== 'string' || typeof item.created !== 'number' || !Number.isSafeInteger(item.created) || Math.abs(now / 1000 - item.created) > 120) return
    const desktopEntry = item.desktopEntry ?? null
    if (desktopEntry !== null && (typeof desktopEntry !== 'string' || !DESKTOP_ENTRY.test(desktopEntry))) return
    const actions = parseActions(item.actions)
    const reply = parseReply(item.reply)
    const defaultAction = item.defaultAction ?? false
    if (!actions || reply === undefined || typeof defaultAction !== 'boolean') return
    return { id: item.id, app: item.app.slice(0, 200), summary: item.summary.slice(0, 500), body: item.body.slice(0, 1000), created: item.created, desktopEntry, actions, defaultAction, reply }
  } catch { return }
}
/** Read and remove private queue files as caboose. Names are generated by the owner's endpoint. */
export const DRAIN_NOTIFICATIONS = `d=/home/caboose/.cache/caboose/notifications
[ -d "$d" ] || exit 0
for f in "$d"/*.json; do
  [ -f "$f" ] || continue
  head -c 32768 "$f"
  printf '\\n'
  rm -f -- "$f"
done`

/** `POST /v1/notifications/:id/respond`: one of the notification's action keys (`default` activates it), or reply text. */
export type NotificationResponse = { action: string } | { reply: string }
export function parseNotificationResponse(input: Record<string, unknown>): NotificationResponse {
  const fields = Object.keys(input)
  if (fields.length !== 1 || (fields[0] !== 'action' && fields[0] !== 'reply')) throw new AgentInputError('Answer with { action } or { reply }')
  if (fields[0] === 'action') {
    if (typeof input.action !== 'string' || !ACTION_KEY.test(input.action)) throw new AgentInputError('action must be 1 to 64 characters without control characters')
    return { action: input.action }
  }
  const reply = input.reply
  if (typeof reply !== 'string' || !reply || reply.includes('\u0000') || /\p{Cs}/u.test(reply) || Array.from(reply).length > REPLY_LIMIT) {
    throw new AgentInputError(`reply must be 1 to ${REPLY_LIMIT} characters of text`)
  }
  return { reply }
}

const NOTIFY = '/opt/caboose/notifications/caboose-notify'
/** Answers a notification through the owner's endpoint, as caboose; a closed or unknown one is a 404. */
export async function respondToNotification(guest: AgentGuest | undefined, id: string, response: NotificationResponse): Promise<{ responded: true }> {
  if (!NOTIFICATION_ID.test(id)) throw new AgentInputError('Invalid notification id')
  if (!guest) throw new AgentUnavailableError()
  const option = 'action' in response ? `--action=${response.action}` : `--reply=${response.reply}`
  const output = await guest.run('/usr/sbin/runuser', ['-u', 'caboose', '--', '/usr/bin/env', 'HOME=/home/caboose',
    'DBUS_SESSION_BUS_ADDRESS=unix:path=/run/user/1000/bus', '/usr/bin/python3', NOTIFY, 'respond', id, option], 20_000)
  let result: unknown
  try { result = (JSON.parse(output.trim().split('\n').pop() ?? '') as { result?: unknown }).result } catch { result = undefined }
  if (result === 'responded') return { responded: true }
  if (result === 'unknown-action') throw new AgentNotFoundError('The notification does not offer that answer')
  if (result === 'unknown-notification') throw new AgentNotFoundError('The notification is no longer on the computer')
  throw new Error('The computer gave an unexpected answer to the notification response')
}

export class DesktopNotifications {
  private timer?: ReturnType<typeof setInterval>
  private polling = false
  private pending?: Promise<void>
  constructor(private guest: () => AgentGuest | undefined, private emit: (event: DesktopNotification) => void) {}
  setActive(active: boolean) {
    if (active && !this.timer) {
      this.timer = setInterval(() => { void this.poll() }, 1000)
      this.timer.unref()
      void this.poll()
    } else if (!active && this.timer) { clearInterval(this.timer); this.timer = undefined }
  }
  async poll() {
    const guest = this.guest()
    if (!guest || this.polling) return
    this.polling = true
    this.pending = (async () => { try {
      const output = await guest.run('/usr/sbin/runuser', ['-u', 'caboose', '--', '/bin/sh', '-c', DRAIN_NOTIFICATIONS], 10_000)
      for (const line of output.split('\n')) {
        const event = parseDesktopNotification(line)
        if (event) this.emit(event)
      }
    } catch (error) { console.error('Desktop notification poll failed:', error instanceof Error ? error.message : 'unknown error') }
    finally { this.polling = false } })()
    try { await this.pending } finally { this.pending = undefined }
  }
  /** Called after polling is disabled, before the guest transport is paused. */
  async quiesce(): Promise<void> { await this.pending }
}
