import type { AgentGuest } from './agents.js'

export interface DesktopNotification { id: string; app: string; summary: string; body: string; created: number }
/** Guest records are untrusted; old entries must not reappear after a host restart. */
export function parseDesktopNotification(line: string, now = Date.now()): DesktopNotification | undefined {
  try {
    const value: unknown = JSON.parse(line)
    if (!value || typeof value !== 'object' || Array.isArray(value)) return
    const item = value as Record<string, unknown>
    if (typeof item.id !== 'string' || !/^[0-9a-f-]{36}$/.test(item.id) || typeof item.app !== 'string' || typeof item.summary !== 'string' || typeof item.body !== 'string' || typeof item.created !== 'number' || !Number.isSafeInteger(item.created) || Math.abs(now / 1000 - item.created) > 120) return
    return { id: item.id, app: item.app.slice(0, 200), summary: item.summary.slice(0, 500), body: item.body.slice(0, 1000), created: item.created }
  } catch { return }
}
/** Read and remove private queue files as caboose. Names are generated by the monitor. */
export const DRAIN_NOTIFICATIONS = `d=/home/caboose/.cache/caboose/notifications
[ -d "$d" ] || exit 0
for f in "$d"/*.json; do
  [ -f "$f" ] || continue
  head -c 32768 "$f"
  printf '\\n'
  rm -f -- "$f"
done`
export class DesktopNotifications {
  private timer?: ReturnType<typeof setInterval>
  private polling = false
  constructor(private guest: () => AgentGuest | undefined, private emit: (event: DesktopNotification) => void) {}
  setActive(active: boolean) {
    if (active && !this.timer) {
      this.timer = setInterval(() => { void this.poll() }, 1000)
      this.timer.unref()
      void this.poll()
    } else if (!active && this.timer) { clearInterval(this.timer); this.timer = undefined }
  }
  async poll() {
    const guest = this.guest()
    if (!guest || this.polling) return
    this.polling = true
    try {
      const output = await guest.run('/usr/sbin/runuser', ['-u', 'caboose', '--', '/bin/sh', '-c', DRAIN_NOTIFICATIONS], 10_000)
      for (const line of output.split('\n')) {
        const event = parseDesktopNotification(line)
        if (event) this.emit(event)
      }
    } catch (error) { console.error('Desktop notification poll failed:', error instanceof Error ? error.message : 'unknown error') }
    finally { this.polling = false }
  }
}
